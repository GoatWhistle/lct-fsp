@dataclass(frozen=True)
class FixedSource:
    catalog: Catalog

    def load(self) -> Catalog:
        return self.catalog


def sync(engine: Engine, catalog: Catalog) -> None:
    """Синхронизация справочника из `catalog` тем же сценарием, что при старте бэкенда."""
    with closing(SqlUnitOfWork(Session(engine))) as uow:
        CatalogSync(uow, SqlCatalog(uow.session), FixedSource(catalog)).run()


def test_models_match_migrations(database_url: str) -> None:
    cfg = Config(BACKEND_DIR / "alembic.ini")
    cfg.attributes["database_url"] = database_url
    cfg.attributes["configure_logger"] = False

    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as diff:
        pytest.fail(f"модели разошлись с миграциями — нужна новая миграция:\n{diff}")


def test_catalog_file_rejects_unknown_topic(tmp_path: Path) -> None:
    broken = tmp_path / "catalog.yaml"
    broken.write_text(
        """
grades: [{code: junior, name: Junior, rank: 1}]
industries: []
specializations:
  - {code: qa, name: QA, topics: [{code: qa.theory, name: Теория}]}
technologies:
  - {code: react, name: React, topics: [frontend.frameworks]}
""",
        encoding="utf-8",
    )

    with pytest.raises(ValueError, match=r"frontend\.frameworks"):
        load_catalog(broken)


def test_catalog_file_in_repo_is_valid() -> None:
    assert isinstance(load_catalog(CATALOG_FILE), Catalog)


def test_catalog_sync_accepts_reordered_grades(database_url: str) -> None:
    original = load_catalog(CATALOG_FILE)
    grades = tuple(replace(g, rank=5 - g.rank) for g in original.grades)
    engine = create_db_engine(database_url)
    try:
        sync(engine, replace(original, grades=grades))
        with engine.connect() as conn:
            rows = conn.execute(text("SELECT code, rank FROM grades"))
            ranks: dict[str, int] = {code: rank for code, rank in rows}
        assert ranks == {"intern": 4, "junior": 3, "middle": 2, "senior": 1}
    finally:
        sync(engine, original)
        engine.dispose()


def catalog_counts(engine: Engine) -> dict[str, int]:
    tables = ["grades", "industries", "specializations", "topics", "technologies"]
    with engine.connect() as conn:
        return {t: conn.scalar(text(f"SELECT count(*) FROM {t}")) or 0 for t in tables} | {
            "technology_topics": conn.scalar(text("SELECT count(*) FROM technology_topics")) or 0
        }


def test_repeated_catalog_sync_changes_nothing(database_url: str) -> None:
    catalog = load_catalog(CATALOG_FILE)
    engine = create_db_engine(database_url)
    try:
        before = catalog_counts(engine)
        sync(engine, catalog)
        sync(engine, catalog)

        assert catalog_counts(engine) == before
        assert before["technologies"] == len(catalog.technologies)
    finally:
        engine.dispose()


def test_catalog_sync_removes_codes_missing_from_file(database_url: str) -> None:
    original = load_catalog(CATALOG_FILE)
    dropped = original.technologies[-1]
    engine = create_db_engine(database_url)
    try:
        sync(engine, replace(original, technologies=original.technologies[:-1]))
        with engine.connect() as conn:
            codes = set(conn.scalars(text("SELECT code FROM technologies")))
        assert dropped.code not in codes
        assert len(codes) == len(original.technologies) - 1
    finally:
        sync(engine, original)
        engine.dispose()
