from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from app.assessment.catalog import CatalogData, load_catalog
from app.config import BACKEND_DIR


def test_models_match_migrations(database_url: str) -> None:
    cfg = Config(BACKEND_DIR / "alembic.ini")
    cfg.attributes["database_url"] = database_url
    cfg.attributes["configure_logger"] = False

    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as diff:
        pytest.fail(f"модели разошлись с миграциями — нужна новая миграция:\n{diff}")


def test_catalog_file_rejects_unknown_topic(tmp_path: Path) -> None:
    broken = tmp_path / "catalog.yaml"
    broken.write_text(
        """
grades: [{code: junior, name: Junior, rank: 1}]
specializations:
  - {code: qa, name: QA, topics: [{code: qa.theory, name: Теория}]}
technologies:
  - {code: react, name: React, topics: [frontend.frameworks]}
""",
        encoding="utf-8",
    )

    with pytest.raises(ValueError, match=r"frontend\.frameworks"):
        load_catalog(broken)


def test_catalog_file_in_repo_is_valid() -> None:
    assert isinstance(load_catalog(), CatalogData)
