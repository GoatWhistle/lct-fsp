import { useRef } from 'react'
import type { Role } from '../api/client'

const OPERATOR = 'Платформа (демо-стенд хакатона)'

type Consent = { purposes: string[]; data: string[] }

// Тексты согласия по 152-ФЗ, ст. 9: оператор, цели, состав данных, действия, срок и отзыв.
const consents: Record<Role, Consent> = {
  candidate: {
    purposes: [
      'подбор вакансий и приглашений от работодателей;',
      'оценка навыков по тесту и построение профиля навыков;',
      'показ работодателям обезличенной карточки, а после принятия приглашения или отклика — профиля с контактами.',
    ],
    data: [
      'email и пароль для входа;',
      'ФИО и контакты — email для связи, телефон, Telegram;',
      'анкета: роли, стаж, стек, софт-скиллы, «о себе», город, готовность к переезду, интересные сферы, ожидаемая зарплата;',
      'ответы на тест и регулярные задания, профиль навыков и категория;',
      'достижения ФСП — если вы привяжете ФСП ID.',
    ],
  },
  employer: {
    purposes: [
      'описание потребностей и подбор кандидатов;',
      'отправка приглашений кандидатам и связь с ними.',
    ],
    data: [
      'email и пароль для входа;',
      'профиль компании и контакты для связи с кандидатами;',
      'потребности, вакансии и приглашения.',
    ],
  },
}

/** Галочка согласия на обработку персональных данных; текст согласия — в модальном окне. */
export function PersonalDataConsent({
  role,
  checked,
  onChange,
}: {
  role: Role
  checked: boolean
  onChange: (checked: boolean) => void
}) {
  const dialog = useRef<HTMLDialogElement>(null)
  const consent = consents[role]
  return (
    <>
      <label className="checkbox">
        <input type="checkbox" required checked={checked} onChange={(e) => onChange(e.target.checked)} />
        <span>
          Согласен на{' '}
          <button type="button" className="link-button" onClick={() => dialog.current?.showModal()}>
            обработку персональных данных
          </button>
        </span>
      </label>
      <dialog ref={dialog} className="modal" aria-labelledby="consent-title">
        <h2 id="consent-title">Согласие на обработку персональных данных</h2>
        <p>
          Регистрируясь, я в соответствии с Федеральным законом от 27.07.2006 № 152-ФЗ «О персональных
          данных» свободно, своей волей и в своём интересе даю согласие оператору — {OPERATOR} — на
          обработку моих персональных данных.
        </p>
        <h3>Цели</h3>
        <ul>
          {consent.purposes.map((p) => (
            <li key={p}>{p}</li>
          ))}
        </ul>
        <h3>Какие данные</h3>
        <ul>
          {consent.data.map((d) => (
            <li key={d}>{d}</li>
          ))}
        </ul>
        <p>
          Оператор может собирать, записывать, систематизировать, хранить, уточнять, использовать,
          передавать в объёме, нужном для целей выше, обезличивать, блокировать, удалять и уничтожать
          данные — с использованием средств автоматизации и без них. Пол, возраст и вуз платформа не
          собирает.
        </p>
        <p>
          Согласие действует до удаления учётной записи или до его отзыва. Отозвать согласие можно,
          написав оператору; после отзыва данные удаляются, если закон не требует их хранить.
        </p>
        {/* Окно лежит внутри формы регистрации: вложенная форма с method="dialog" недопустима. */}
        <div className="actions">
          <button type="button" className="button" onClick={() => dialog.current?.close()}>
            Понятно
          </button>
        </div>
      </dialog>
    </>
  )
}
